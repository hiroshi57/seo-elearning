function main() {
  let changed = 0;
  for (const [slug, items] of Object.entries(HARDEN)) {
    const file = path.join(CH_DIR, `${slug}.json`);
    if (!fs.existsSync(file)) {
      console.warn("skip (not found):", slug);
      continue;
    }
    const j = JSON.parse(fs.readFileSync(file, "utf8"));
    const byId = new Map((j.quiz || []).map((q) => [q.id, q]));
    let n = 0;
    for (const it of items) {
      const q = byId.get(it.id);
      if (!q) {
        console.warn(`  ${slug}: id not found ->`, it.id);
        continue;
      }
      if (it.question) q.question = it.question;
      if (it.type) q.type = it.type;
      if (it.options) q.options = it.options;
      if (it.correct) q.correct = it.correct;
      if (it.explain) q.explain = it.explain;
      n++;
      changed++;
    }
    if (n) {
      writeJson(file, j);
      console.log(`updated ${slug}: ${n}問を難化`);
    }
  }
  console.log(`\n完了: 合計 ${changed}問を難化しました。（このあと quiz-shuffle-answers.js を実行）`);
}
main();
