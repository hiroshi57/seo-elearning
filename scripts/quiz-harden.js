function writeJson(file, obj) {
  let out = JSON.stringify(obj, null, 2) + "\n";
  out = out.replace(
    /("correct":\s*)\[\s*([\d,\s]*?)\s*\]/g,
    (m, k, nums) => k + "[" + nums.replace(/\s+/g, "").split(",").filter((s) => s !== "").join(", ") + "]"
  );
  fs.writeFileSync(file, out, "utf8");
}

